"""Parser for OpenSMOKE kinetic mechanisms.

Reads the mechanism XML (kinetic parameters and species) together with the
reaction table ``.out`` file and converts the molar stoichiometry of the solid
products into mass yields. The resulting mechanism can be exported to JSON so
the ODE solver does not need to parse the original files on every run.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Optional


DEFAULT_XML = Path(__file__).resolve().parent.parent / "data" / "kinetics" / "kinetics.solid.xml"
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "data" / "kinetics" / "Reaction_Tables_Solid.out"
DEFAULT_JSON = Path(__file__).resolve().parent.parent / "data" / "kinetics" / "cineticas_solidas.json"


class MecanismoCinetico:
    """Kinetic mechanism with molar-to-mass stoichiometry mapping.

    Parameters
    ----------
    xml_path:
        Path to the OpenSMOKE mechanism XML file.
    out_path:
        Path to the reaction table generated by OpenSMOKE.
    """

    def __init__(self, xml_path: str | Path, out_path: str | Path):
        self.xml_path = Path(xml_path)
        self.out_path = Path(out_path)
        self.species: List[str] = []
        self.solid_species: List[str] = []
        self.reactions: List[dict] = []
        self.MW: Dict[str, float] = {}

        self.parse_xml()
        self.parse_out()

    def parse_xml(self) -> None:
        tree = ET.parse(self.xml_path)
        root = tree.getroot()

        species_text = root.find(".//NamesOfSpecies").text
        self.species = species_text.split()

        solid_species_text = root.find(".//SolidSpecies").text
        self.solid_species = solid_species_text.split()

        comp_text = root.find(".//AtomicComposition").text
        lines = comp_text.strip().split("\n")

        elements = root.find(".//NamesOfElements").text.split()
        mw_elem = {"C": 12.011, "H": 1.008, "O": 15.999, "N": 14.007, "K": 39.098}
        mw_array = [mw_elem.get(e, 0.0) for e in elements]

        for i, line in enumerate(lines):
            if i >= len(self.species):
                break
            atoms = [float(x) for x in line.split()]
            self.MW[self.species[i]] = sum(a * m for a, m in zip(atoms, mw_array))

        kinematics = root.find(".//Direct")
        lnA_vals = kinematics.find("lnA").text.split()[1:]
        beta_vals = kinematics.find("Beta").text.split()[1:]
        E_R_vals = kinematics.find("E_over_R").text.split()[1:]

        for i in range(len(lnA_vals)):
            self.reactions.append(
                {
                    "id": i + 1,
                    "lnA": float(lnA_vals[i]),
                    "beta": float(beta_vals[i]),
                    "E_R": float(E_R_vals[i]),
                    "reactant": None,
                    "solid_products": {},
                }
            )

    def parse_out(self) -> None:
        with open(self.out_path, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()

        for i, line in enumerate(lines):
            if not line.startswith(" KINETIC DATA - REACTION"):
                continue

            rxn_num = int(line.split()[4])
            eq_line = lines[i + 1].strip()
            if "=>" not in eq_line:
                continue

            reactant_str, products_str = eq_line.split("=>")
            reactant = reactant_str.strip()
            products = [p.strip() for p in products_str.split("+")]

            solid_prods: Dict[str, float] = {}
            for p in products:
                if not p:
                    continue
                match = re.match(r"^([\d\.]+)?(.*)$", p)
                if not match:
                    continue

                coeff_str = match.group(1)
                species = match.group(2)
                molar_coeff = float(coeff_str) if coeff_str else 1.0

                if species in self.solid_species:
                    # Molar -> mass yield: coeff_mass = coeff_molar * MW_prod / MW_react
                    mass_coeff = molar_coeff * (self.MW[species] / self.MW[reactant])
                    solid_prods[species] = solid_prods.get(species, 0.0) + mass_coeff

            self.reactions[rxn_num - 1]["reactant"] = reactant
            self.reactions[rxn_num - 1]["solid_products"] = solid_prods

    def solid_reactions(self) -> List[dict]:
        """Return only reactions whose reactant is a solid species."""
        return [r for r in self.reactions if r["reactant"] in self.solid_species]

    def to_dict(self) -> dict:
        return {
            "solid_species": self.solid_species,
            "reactions": self.solid_reactions(),
        }

    def export_json(self, json_path: str | Path = DEFAULT_JSON) -> Path:
        json_path = Path(json_path)
        json_path.parent.mkdir(parents=True, exist_ok=True)
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(self.to_dict(), f, indent=4)
        return json_path


def exportar_cineticas(
    xml_path: str | Path = DEFAULT_XML,
    out_path: str | Path = DEFAULT_OUT,
    json_path: str | Path = DEFAULT_JSON,
) -> Path:
    """Parse an OpenSMOKE mechanism and export the solid reactions to JSON."""
    mechanism = MecanismoCinetico(xml_path, out_path)
    return mechanism.export_json(json_path)


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Export solid kinetics to JSON")
    parser.add_argument("--xml", default=str(DEFAULT_XML))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--json", default=str(DEFAULT_JSON))
    args = parser.parse_args()

    path = exportar_cineticas(args.xml, args.out, args.json)
    print(f"Solid mechanism exported to: {path}")
